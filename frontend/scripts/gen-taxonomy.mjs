// Generates src/lib/generated/taxonomy.ts from the backend's data files, so the browser
// suggests the same skill names, industry tags and country codes the API accepts.
//
//   npm run gen:taxonomy          write the file
//   (taxonomy.test.ts fails when the committed file is out of date)
//
// The YAML files use one flow-style entry per line, so a line parser is enough and the
// frontend needs no YAML dependency.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const DATA_DIR = resolve(HERE, "../../backend/app/ingest/data");
export const OUT_FILE = resolve(HERE, "../src/lib/generated/taxonomy.ts");

function unquote(value) {
  const v = value.trim();
  if ((v.startsWith("'") && v.endsWith("'")) || (v.startsWith('"') && v.endsWith('"'))) return v.slice(1, -1);
  return v;
}

/** Split a flow list body on commas outside quotes and brackets. */
function splitList(body) {
  const items = [];
  let current = "";
  let quote = null;
  let depth = 0;
  for (const ch of body) {
    if (quote) {
      if (ch === quote) quote = null;
      current += ch;
    } else if (ch === "'" || ch === '"') {
      quote = ch;
      current += ch;
    } else if (ch === "[") {
      depth += 1;
      current += ch;
    } else if (ch === "]") {
      depth -= 1;
      current += ch;
    } else if (ch === "," && depth === 0) {
      items.push(current);
      current = "";
    } else {
      current += ch;
    }
  }
  if (current.trim()) items.push(current);
  return items.map(unquote).filter(Boolean);
}

/** skills.yaml: canonical names in file order, and lower-cased alias -> canonical name. */
export function parseSkills(text) {
  const skills = [];
  const aliases = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^ {2}(.+?): \{aliases: \[(.*?)\](?:, .*)?\}\s*$/.exec(line);
    if (!m) continue;
    const name = unquote(m[1]);
    skills.push(name);
    aliases[name.toLowerCase()] = name;
    for (const alias of splitList(m[2])) {
      if (alias.startsWith("re:")) continue; // regexes only match job text
      aliases[alias.toLowerCase()] = name;
    }
  }
  return { skills, aliases };
}

/** companies.yaml: every industry tag used, sorted. */
export function parseIndustries(text) {
  const tags = new Set();
  for (const m of text.matchAll(/industries: \[([^\]]*)\]/g)) {
    for (const tag of splitList(m[1])) tags.add(tag.toLowerCase());
  }
  return [...tags].sort();
}

/** locations.yaml: the ISO codes under `countries:`, the ones the API accepts. */
export function parseCountryCodes(text) {
  const codes = [];
  let inCountries = false;
  for (const line of text.split(/\r?\n/)) {
    if (/^\S/.test(line)) inCountries = line.startsWith("countries:");
    if (!inCountries) continue;
    const m = /^ {2}['"]?([A-Z]{2})['"]?:/.exec(line);
    if (m) codes.push(m[1]);
  }
  return codes;
}

export function render() {
  const read = (name) => readFileSync(resolve(DATA_DIR, name), "utf8");
  const { skills, aliases } = parseSkills(read("skills.yaml"));
  const industries = parseIndustries(read("companies.yaml"));
  const countries = parseCountryCodes(read("locations.yaml"));
  const json = (value) => JSON.stringify(value, null, 2);
  return `// Generated by scripts/gen-taxonomy.mjs from backend/app/ingest/data. Do not edit.
// Regenerate with \`npm run gen:taxonomy\`.

/** Canonical skill names (skills.yaml), in taxonomy order. */
export const SKILLS: readonly string[] = ${json(skills)};

/** Lower-cased name or alias -> canonical name, as the backend's canonical_skill() maps them. */
export const SKILL_ALIASES: Readonly<Record<string, string>> = ${json(aliases)};

/** Industry tags used in companies.yaml (what exclude_industries compares against). */
export const INDUSTRIES: readonly string[] = ${json(industries)};

/** ISO 3166-1 alpha-2 codes the API accepts for countries (locations.yaml). */
export const COUNTRY_CODES: readonly string[] = ${json(countries)};
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT_FILE, render());
  console.log(`wrote ${OUT_FILE}`);
}
